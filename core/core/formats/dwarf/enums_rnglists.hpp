namespace pepp::bts {
// Range list (.debug_rnglists) enumerated constants, per Sections 2.17.3 and 7.25.

// Per: Table 7.30. The single byte that begins each range list entry (Section 2.17.3).
enum class RangeListEntries : u8 {
  DW_RLE_end_of_list = 0x00,
  DW_RLE_base_addressx = 0x01,
  DW_RLE_startx_endx = 0x02,
  DW_RLE_startx_length = 0x03,
  DW_RLE_offset_pair = 0x04,
  DW_RLE_base_address = 0x05,
  DW_RLE_start_end = 0x06,
  DW_RLE_start_length = 0x07,
};
} // namespace pepp::bts
